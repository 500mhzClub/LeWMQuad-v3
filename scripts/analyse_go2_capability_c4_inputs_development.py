"""Interpretation-only analysis of C4's inputs (Andrew Knowles, 28 September 2026).

C4 receives the candidate command tape directly, so it may mostly learn kinematics.
Nothing here changes any controller or result.

Part A (logs only): C4's logged motion predictions versus C1's command-history
forecasts, which the shared runtime computes and logs on the same decision inputs.
Part B: native model inputs for a fixed decision sample are regenerated by a
verified deterministic replay of logged C4 episodes (no new outcomes), then C4
is re-evaluated with its own visual features (must reproduce the log) and with
visual features swapped from another decision (other maze; same maze later).
"""
