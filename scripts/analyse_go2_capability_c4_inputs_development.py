    p = argparse.ArgumentParser()
    p.add_argument('--phase', choices=('logs', 'capture', 'swap'), required=True)
    p.add_argument('--out', type=Path, required=True)
    args = p.parse_args()
    protocol = json.loads(owner.PROTOCOL.read_text())
    base = Path(protocol['output_root'])
    assert args.out.resolve().is_relative_to(base.resolve())
    output.install(base)
    args.out.mkdir(parents=True, exist_ok=True)
    if args.phase == 'logs':
        result = part_a(base)
        owner.save(args.out/'c4_vs_c1_logged_agreement.json', result)
    elif args.phase == 'capture':
        result = {m: capture(base, base/f'runs/v4_completed_support_validation_C4_val{m:02d}_ep0_attempt001', args.out) for m in SAMPLE_EPISODES}
    else:
        result = part_b(base, args.out)
        owner.save(args.out/'c4_visual_swap.json', result)
    print(json.dumps(result, indent=1)[:4000])
